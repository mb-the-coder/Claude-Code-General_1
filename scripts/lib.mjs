/** Third-party packages the backend imports. In production Deno loads them from npm; they are not inlined. */
export const NPM_DEPS = ['zod', 'zod-to-json-schema', 'node-html-parser'];

export function npmSpecifier(pkg) {
  const { version } = JSON.parse(readFileSync(path.join(ROOT, 'node_modules', pkg, 'package.json'), 'utf8'));
  return `npm:${pkg}@${version}`;
}

/** esbuild plugin: rewrite bare imports of NPM_DEPS to pinned `npm:` specifiers and leave them external. */
const denoNpmPlugin = {
  name: 'deno-npm',
  setup(b) {
    b.onResolve({ filter: new RegExp(`^(${NPM_DEPS.join('|')})$`) }, (args) => ({ path: npmSpecifier(args.path), external: true }));
  },
};

/**
 * Bundles one backend function into a single ES module for Base44's Deno runtime.
 * Our own sources (functions, utils, lib/ai) are inlined. Third-party packages are imported by Deno from npm
 * at pinned versions (`npm:zod@x.y.z`), exactly like the platform SDK, which keeps each file small enough to
 * review and edit. Pass `npmDeps: false` to inline them instead (used to execute the bundle under Node in tests).
 */
export async function bundleFunction(name, { alias = {}, external = ['npm:*'], minify = false, npmDeps = true } = {}) {
  const result = await build({
    entryPoints: [path.join(ROOT, 'backend', 'functions', `${name}.ts`)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    conditions: ['import', 'module', 'default'],
    external,
    alias,
    minify,
    legalComments: 'none',
    logLevel: 'silent',
    plugins: npmDeps ? [denoNpmPlugin] : [],
    banner: {
      js: `// GENERATED by scripts/assemble-base44.mjs from backend/functions/${name}.ts - edit the source, then rebuild.`,
    },
  });
  return result.outputFiles[0].text;
}

/**
 * Walks the import graph of the page entry and returns every local source file it pulls in
 * (paths relative to the repo root). Used to prove FRONTEND_FILES is complete and backend-free.
 */
export async function frontendImportGraph(entry = 'pages/OmniCompetitor.tsx', { root = ROOT } = {}) {
  const result = await build({
    entryPoints: [path.join(root, entry)],
    bundle: true,
    write: false,
    metafile: true,
    format: 'esm',
    platform: 'browser',
    jsx: 'automatic',
    logLevel: 'silent',
    // Provided by the host Base44 app / npm, not part of our source tree.
    external: ['react', 'react/*', 'react-dom', 'react-dom/*', '@tanstack/react-query', 'lucide-react', '@/api/base44Client'],
  });
  return Object.keys(result.metafile.inputs)
    .filter((p) => !p.includes('node_modules'))
    .map((p) => path.relative(root, path.resolve(root, p)).split(path.sep).join('/'))
    .sort();
}

/** Returns import specifiers in the bundle that the Deno runtime could not resolve. */
export function findUnresolvedImports(code) {
  const specifiers = [...code.matchAll(/(?:^|\n)\s*(?:import|export)\s[^;\n]*?from\s*["']([^"']+)["']/g)].map((m) => m[1]);
  return specifiers.filter((s) => !s.startsWith('npm:'));
}
