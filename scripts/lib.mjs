/**
 * Bundles one backend function into a single self-contained ES module for Base44's Deno runtime.
 * Local imports plus zod, zod-to-json-schema and node-html-parser are inlined; only `npm:` specifiers
 * (the Base44 SDK) stay external because the platform provides them.
 */
export async function bundleFunction(name, { alias = {}, external = ['npm:*'], minify = false } = {}) {
  const result = await build({
    entryPoints: [path.join(ROOT, 'backend', 'functions', `${name}.ts`)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    conditions: ['import', 'module', 'default'],
    external,
    alias,
    minify,
    legalComments: 'none',
    logLevel: 'silent',
    banner: {
      js: `// GENERATED by scripts/assemble-base44.mjs from backend/functions/${name}.ts - edit the source, then rebuild.`,
    },
  });
  return result.outputFiles[0].text;
}

/** Returns import specifiers in the bundle that the Deno runtime could not resolve. */
export function findUnresolvedImports(code) {
  const specifiers = [...code.matchAll(/(?:^|\n)\s*(?:import|export)\s[^;\n]*?from\s*["']([^"']+)["']/g)].map((m) => m[1]);
  return specifiers.filter((s) => !s.startsWith('npm:'));
}
